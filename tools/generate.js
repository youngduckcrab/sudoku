#!/usr/bin/env node
/* Builds js/puzzles.js: a bank of graded puzzles.
 * Usage: node tools/generate.js [countPerLevel=150] [seed]
 * Every puzzle has a unique solution and is fully solvable by the hint engine. */
'use strict';
const path = require('path');
const fs = require('fs');
const C = require('../js/core.js');
const T = require('../js/techniques.js');
const { grade, makePuzzle: mk } = require('../js/generator.js');

const target = parseInt(process.argv[2] || '150', 10);
const seed = parseInt(process.argv[3] || String(Date.now() % 1e9), 10);
const rng = C.mulberry32(seed);

const makePuzzle = () => mk(rng);

const bank = { hard: [], expert: [] };
const stats = {};
let tries = 0;
const t0 = Date.now();
while (bank.hard.length < target || bank.expert.length < target) {
  tries++;
  const { puzzle, solution } = makePuzzle();
  const r = T.solveLogically(puzzle);
  // Soundness check: the logical result must match the backtracking solution.
  if (r.solved && r.grid.some((v, i) => v !== solution[i])) throw new Error('Unsound technique on ' + C.stringify(puzzle));
  const level = grade(r);
  stats[level] = (stats[level] || 0) + 1;
  const str = C.stringify(puzzle);
  if (level === 'hard' && bank.hard.length < target) bank.hard.push(str);
  if (level === 'expert' && bank.expert.length < target) bank.expert.push(str);
  if (tries % 200 === 0) console.error(`tries=${tries} hard=${bank.hard.length} expert=${bank.expert.length} ${JSON.stringify(stats)} ${((Date.now() - t0) / 1000).toFixed(0)}s`);
}
const out = `/* Generated by tools/generate.js (seed ${seed}). Puzzles are shuffled further at runtime. */\n` +
  `(function (root) {\n  var BANK = ${JSON.stringify(bank, null, 0).replace(/","/g, '",\n"')};\n` +
  `  if (typeof module !== 'undefined' && module.exports) module.exports = BANK; else root.PUZZLE_BANK = BANK;\n` +
  `})(typeof self !== 'undefined' ? self : this);\n`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'puzzles.js'), out);
console.error('done', stats, `${((Date.now() - t0) / 1000).toFixed(1)}s`);
